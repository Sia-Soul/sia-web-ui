const assert = require('node:assert/strict');
const {chromium} = require(require('node:path').join(process.argv[2], 'playwright'));
(async () => {
 const browser = await chromium.launch({headless:true, channel:'msedge'});
 try {
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];page.on('pageerror', e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:4173/components/query-form');
  const query=page.locator('.sia-query-form').first();
  const result=page.getByLabel('查询结果说明');
  await query.getByRole('textbox',{name:'品牌方名称',exact:true}).fill('旧条件');
  await query.getByRole('button',{name:'待审核',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="查询结果说明"]').textContent.includes('已查询 1 次'));
  assert.equal(await query.getByRole('textbox',{name:'品牌方名称',exact:true}).inputValue(),'');
  assert((await result.innerText()).includes('quick，共 1 条'));
  assert.deepEqual(JSON.parse(await page.getByLabel('当前查询条件').innerText()).status,['pending']);
  await query.getByRole('button',{name:'重置',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('[aria-label="查询结果说明"]').textContent.includes('已查询 2 次'));
  assert((await result.innerText()).includes('reset，共 3 条'));
  await query.getByRole('textbox',{name:'备注',exact:true}).fill('保留条件');
  await query.getByRole('button',{name:'收起',exact:true}).click();
  assert((await query.locator('.sia-query-form__field:visible').count()) <= 3);
  await query.getByRole('button',{name:'展开',exact:true}).click();
  assert.equal(await query.getByRole('textbox',{name:'备注',exact:true}).inputValue(),'保留条件');
  const tag=query.getByLabel('已保存快捷查询').locator('.sia-tag').first();
  await tag.focus();await page.keyboard.press('Enter');
  await page.waitForFunction(()=>document.querySelector('[aria-label="查询结果说明"]').textContent.includes('已查询 3 次'));
  assert((await result.innerText()).includes('saved，共 1 条'));
  assert.equal(await query.getByRole('textbox',{name:'备注',exact:true}).inputValue(),'');
  await query.getByRole('button',{name:'另存为快捷查询',exact:true}).click();
  const dialog=page.getByRole('dialog');await dialog.waitFor();
  await dialog.getByRole('button',{name:'确定',exact:true}).click();
  await dialog.getByRole('alert').waitFor();
  await dialog.getByRole('textbox',{name:'快捷查询名称',exact:true}).fill(' 成都查询 ');
  await dialog.getByRole('button',{name:'确定',exact:true}).click();
  await dialog.waitFor({state:'hidden'});
  const saved=query.getByLabel('已保存快捷查询').locator('.sia-tag').filter({hasText:'成都查询'});
  await saved.waitFor();
  await saved.getByRole('button',{name:'移除标签'}).click();
  await saved.waitFor({state:'detached'});
  assert((await result.innerText()).includes('已查询 3 次'));
  await query.getByRole('textbox',{name:'品牌方名称',exact:true}).fill('办公');
  await query.getByRole('textbox',{name:'品牌方名称',exact:true}).press('Enter');
  await page.waitForFunction(()=>document.querySelector('[aria-label="查询结果说明"]').textContent.includes('已查询 4 次'));
  assert((await result.innerText()).includes('submit，共 1 条'));
  await page.screenshot({path:require('node:path').join(process.env.TEMP,'query-form-preview.png')});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(250);
  assert(await query.evaluate(el=>el.scrollWidth<=el.clientWidth+1));
  assert.deepEqual(errors,[]);
  console.log('PASS query, reset, shortcut replacement and keyboard, collapse, save validation, deletion isolation, mobile layout');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
