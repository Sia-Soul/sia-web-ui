const assert=require('node:assert/strict');
const path=require('node:path');
const localRequire=require('node:module').createRequire(path.resolve('packages/react/package.json'));
const React=localRequire('react');
const {renderToStaticMarkup}=localRequire('react-dom/server');
const {CandlestickChart}=localRequire('./dist/chart.cjs');
const data=Array.from({length:4},(_,i)=>({name:`日期${i}`,open:10+i,close:12+i,low:9+i,high:14+i}));
const render=extra=>renderToStaticMarkup(React.createElement(CandlestickChart,{data,seriesName:'指数',animation:false,...extra}));
const count=html=>(html.match(/class="sia-chart__candlestick"/g)||[]).length;
assert.equal(count(render({})),4);
assert.equal(count(render({seriesVisible:false})),0);
assert.equal(count(render({seriesVisible:true})),4);
assert.ok(!render({showLegend:false}).includes('sia-chart__legend'));
assert.ok(!render({activeIndex:null}).includes('data-candlestick-active-index'));
assert.ok(!render({activeIndex:99}).includes('data-candlestick-active-index'));
const selected=render({appearance:'macarons',dataZoom:true,zoom:[50,100],activeIndex:2,plotBounds:{x:80,y:40,width:600,height:180}});
assert.equal(count(selected),2);
assert.match(selected,/data-candlestick-active-index="2" x="80" y="40" width="300" height="180"/);
assert.ok(!render({appearance:'macarons',dataZoom:true,zoom:[50,100],activeIndex:0}).includes('data-candlestick-active-index'));
assert.ok(!render({seriesVisible:false,activeIndex:2}).includes('data-candlestick-active-index'));
assert.ok(!render({showCategoryLabels:false}).includes('class="sia-chart__axis-label">日期'));
console.log('K线受控接口：默认兼容、显隐、隐藏图例/日期、全量索引映射缩放窗口、空/越界高亮和自定义绘图区通过。');
