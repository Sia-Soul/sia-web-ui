const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require(path.join(process.argv[2],'playwright'));
const option=JSON.parse(fs.readFileSync('apps/docs/src/pages/chartMixedWaterSource.json','utf8'))[0].option;
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.argv[3]});
 try{
  const page=await browser.newPage({viewport:{width:1500,height:1100}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://localhost:4174/components/chart?reference='+encodeURIComponent('http://static.dtws110.com/echarts-2.2.7/doc/example/mix1.html'));
  const preview=page.locator('.chart-mixed-water');await preview.waitFor();
  const labels=await preview.locator('[data-mixed-series]').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('aria-label')).sort());
  assert.deepEqual(labels,option.series.flatMap(item=>item.data.map((value,index)=>`${item.name}，${option.xAxis[0].data[index]}，${value}`)).sort());
  assert.equal(await preview.locator('[data-mixed-series] rect').count(),24);
  assert.equal(await preview.locator('[data-mixed-series] circle').count(),12);
  assert.ok((await preview.locator('[data-value-axis="0"]').textContent()).includes('ml'));
  assert.ok((await preview.locator('[data-value-axis="1"]').textContent()).includes('°C'));
  await preview.locator('[data-mixed-axis-tooltip="0"]').focus();
  const tip=preview.getByRole('tooltip');await tip.waitFor();
  assert.ok((await tip.innerText()).includes('平均温度：2'));
  await preview.getByRole('button',{name:'平均温度',exact:true}).click();
  assert.equal(await preview.locator('[data-mixed-series]').count(),24);
  await preview.getByRole('button',{name:'平均温度',exact:true}).click();
  await preview.getByRole('button',{name:'切换为折线图',exact:true}).click();
  assert.equal(await preview.locator('[data-mixed-series] circle').count(),36);
  await preview.getByRole('button',{name:'切换为柱状图',exact:true}).click();
  assert.equal(await preview.locator('[data-mixed-series] rect').count(),36);
  await preview.getByRole('button',{name:'还原',exact:true}).click();
  assert.equal(await preview.locator('[data-mixed-series] circle').count(),12);
  await preview.getByRole('button',{name:'数据视图',exact:true}).click();
  const editor=preview.getByRole('textbox',{name:'图表数值数据'});
  const data=JSON.parse(await editor.inputValue());assert.deepEqual(data,option.series.map(item=>item.data));
  data[2][0]=9;await editor.fill(JSON.stringify(data));await preview.getByRole('button',{name:'应用数据',exact:true}).click();
  assert.equal(await preview.locator('[aria-label="平均温度，1月，9"]').count(),1);
  await preview.getByRole('button',{name:'关闭数据视图',exact:true}).click();
  await preview.getByRole('button',{name:'还原',exact:true}).click();
  await preview.scrollIntoViewIfNeeded();await page.waitForTimeout(800);
  const source=await preview.locator('[data-mixed-series="0"][data-mixed-index="7"]').boundingBox();
  const target=await preview.locator('[data-mixed-series="0"][data-mixed-index="6"]').boundingBox();
  assert.ok(source&&target);
  await page.mouse.move(source.x+source.width/2,source.y+source.height/2);await page.mouse.down();
  await page.mouse.move(target.x+target.width/2,target.y+target.height/2,{steps:20});await page.mouse.up();
  assert.equal(await preview.locator('[aria-label="蒸发量，7月，297.8"]').count(),1);
  assert.equal(await preview.locator('[aria-label="蒸发量，8月，空槽"]').count(),1);
  await preview.getByRole('button',{name:'还原',exact:true}).click();await page.waitForTimeout(800);
  await preview.screenshot({path:'apps/docs/chart-mix1-preview.png'});
  assert.deepEqual(errors,[]);
  await page.goto('http://localhost:4174/components/chart/mix');
  const card=page.locator('#chart-example-mix1');await card.scrollIntoViewIfNeeded();
  await card.locator('.chart-mixed-water').waitFor();
  assert.equal(await page.locator('.chart-reference-card').count(),12);
  console.log('mix1：36 原始数据、24 柱/12 点、双轴单位、图例、轴提示、切换、编辑与还原通过。');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
