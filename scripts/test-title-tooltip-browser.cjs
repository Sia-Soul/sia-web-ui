const assert = require('node:assert/strict');
const { chromium } = require(require('node:path').join(process.argv[2], 'playwright'));
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.argv[3] });
  try {
    const page = await browser.newPage();
    await page.goto('http://127.0.0.1:4173/components/button');
    const button = page.getByRole('button', { name: '更多操作提示示例', exact: true });
    const tip = page.locator('.sia-title-tooltip');
    await button.hover(); await page.waitForTimeout(300);
    assert.equal(await tip.count(), 0, 'Quick hover must not show title');
    await page.mouse.move(0, 0); await page.waitForTimeout(400);
    assert.equal(await tip.count(), 0, 'Leaving cancels pending title');
    await button.hover(); await tip.waitFor();
    assert.equal(await button.getAttribute('title'), null);
    assert.equal(await tip.innerText(), '查看其他操作');
    assert.ok(await button.getAttribute('aria-describedby'));
    const light = await tip.evaluate(el => getComputedStyle(el).backgroundColor);
    await page.keyboard.press('Escape'); await tip.waitFor({ state: 'hidden' });
    assert.equal(await button.getAttribute('aria-describedby'), null);
    await page.getByRole('button', { name: '禁用提示示例', exact: true }).hover();
    await tip.waitFor(); assert.equal(await tip.innerText(), '当前操作不可用');
    const input = page.getByRole('textbox', { name: '标题提示输入框' });
    await page.mouse.move(0, 0); await input.focus(); await tip.waitFor();
    assert.equal(await tip.innerText(), '请输入项目名称');
    await input.evaluate(el => el.setAttribute('data-sia-title', '更新后的提示'));
    await page.waitForTimeout(100); assert.equal(await tip.innerText(), '更新后的提示');
    await page.getByRole('button', { name: '显式提示示例', exact: true }).hover();
    await page.waitForTimeout(400); assert.equal(await tip.count(), 0);
    assert.equal(await page.getByRole('tooltip').innerText(), '显式 Tooltip 优先');
    await page.locator('.sia-theme-switch').click();
    await button.hover(); await tip.waitFor();
    assert.notEqual(await tip.evaluate(el => getComputedStyle(el).backgroundColor), light);
    await button.evaluate(el => el.remove());
    await tip.waitFor({ state: 'hidden' });
    await page.goto('http://127.0.0.1:4173/components/typography');
    const internal = page.locator('.sia-typography__action[data-sia-title]').first();
    await internal.scrollIntoViewIfNeeded();
    await page.waitForTimeout(200);
    await internal.hover(); await tip.waitFor();
    assert.equal(await internal.getAttribute('title'), null);
    assert.equal(await tip.innerText(), await internal.getAttribute('data-sia-title'));
    await page.evaluate(() => document.dispatchEvent(new Event('scroll')));
    await tip.waitFor({ state: 'hidden' });
    const bounds = await internal.boundingBox();
    await page.mouse.move(bounds.x + bounds.width / 2 + 1, bounds.y + bounds.height / 2);
    await tip.waitFor();
    await page.mouse.move(0, 0);
    await tip.waitFor({ state: 'hidden' });
    console.log('PASS: native title suppression, hover/focus/disabled, Escape, dynamic text, explicit Tooltip precedence, theme switching, removal cleanup, internal controls, scroll recovery and mouse leave');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
