const assert=require('node:assert/strict');
const path=require('node:path');
const {chromium}=require(path.join(process.argv[2],'playwright'));
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.argv[3]});
 try{
  const page=await browser.newPage({viewport:{width:1500,height:1100}});
  await page.goto('http://localhost:4174/components/chart?reference='+encodeURIComponent('http://static.dtws110.com/echarts-2.2.7/doc/example/mix2.html'));
  const preview=page.locator('.chart-mixed-traffic');await preview.waitFor();
  assert.equal(await preview.locator('.sia-chart__legend [role="button"]').count(),9);
  await preview.getByRole('button',{name:'百度',exact:true}).click();
  assert.equal(await preview.locator('[role="graphics-symbol"][aria-label*="百度"]').count(),0);
  await preview.getByRole('button',{name:'百度',exact:true}).click();
  assert.equal(await preview.locator('[role="graphics-symbol"][aria-label*="百度"]').count(),1);
  const baidu=preview.locator('[role="graphics-symbol"][aria-label="搜索引擎细分，百度，1048"]');
  await baidu.focus();
  const pieTooltip=preview.getByRole('tooltip');await pieTooltip.waitFor();
  assert.match(await pieTooltip.innerText(),/搜索引擎细分/);
  assert.match(await pieTooltip.innerText(),/百度：1048 \(67\.7%\)/);
  const toolbar=await preview.getByRole('toolbar').boundingBox(),bounds=await preview.boundingBox();
  assert.ok(toolbar&&bounds&&toolbar.y>bounds.y+bounds.height*.8);
  // PieChart defaults to a 2-second entry animation; export its completed frame.
  await page.waitForTimeout(2300);
  const downloadEvent=page.waitForEvent('download');
  await preview.getByRole('button',{name:'保存为图片',exact:true}).click();
  const download=await downloadEvent;
  assert.equal(download.suggestedFilename(),'mix2.png');
  await download.saveAs(path.resolve('apps/docs/chart-mix2-export.png'));
  const cell=series=>preview.locator(`[data-mixed-series="${series}"][data-mixed-index="0"]`);
  const x=series=>cell(series).locator('rect').getAttribute('x');
  assert.equal(await x(1),await x(2));
  await cell(1).focus();
  let tooltip=preview.getByRole('tooltip');await tooltip.waitFor();
  assert.ok((await tooltip.innerText()).includes('邮件营销'));
  assert.ok(!(await tooltip.innerText()).includes('联盟广告'));
  await preview.locator('[data-mixed-axis-tooltip="0"]').focus();
  assert.ok((await tooltip.innerText()).includes('联盟广告'));
  await preview.getByRole('button',{name:'切换为平铺',exact:true}).click();
  assert.notEqual(await x(1),await x(2));
  await preview.getByRole('button',{name:'还原',exact:true}).click();
  assert.equal(await x(1),await x(2));
  assert.equal(await preview.locator('[data-mixed-series]').count(),35);
  await preview.getByRole('button',{name:'数据视图',exact:true}).click();
  const editor=preview.getByRole('textbox',{name:'图表数值数据'});
  const data=JSON.parse(await editor.inputValue());
  assert.deepEqual(data.map(row=>row.length),[7,7,7,7,7,4]);
  assert.deepEqual(data[5],[1048,251,147,102]);
  data[0][0]=321;data[5][0]=500;
  await editor.fill(JSON.stringify(data));await preview.getByRole('button',{name:'应用数据',exact:true}).click();
  assert.equal(await preview.locator('[aria-label="直接访问，周一，321"]').count(),1);
  assert.equal(await preview.locator('[role="graphics-symbol"][aria-label*="百度"][aria-label*="500"]').count(),1);
  data[5][0]=-1;
  await editor.fill(JSON.stringify(data));await preview.getByRole('button',{name:'应用数据',exact:true}).click();
  assert.ok((await preview.getByRole('alert').innerText()).includes('非负'));
  assert.equal(await preview.locator('[role="graphics-symbol"][aria-label*="百度"][aria-label*="500"]').count(),1);
  await preview.getByRole('button',{name:'关闭数据视图',exact:true}).click();
  await preview.getByRole('button',{name:'还原',exact:true}).click();
  assert.equal(await preview.locator('[aria-label="直接访问，周一，320"]').count(),1);
  assert.equal(await preview.locator('[role="graphics-symbol"][aria-label*="百度"][aria-label*="1048"]').count(),1);
  await preview.scrollIntoViewIfNeeded();
  const rect=await cell(0).boundingBox();assert.ok(rect);
  await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);await page.mouse.down();
  await page.mouse.move(20,100,{steps:20});await page.mouse.up();
  assert.equal(await preview.locator('[data-mixed-series="-1"]').count(),1);
  await preview.getByRole('button',{name:'数据视图',exact:true}).click();
  assert.equal(JSON.parse(await editor.inputValue())[0][0],null);
  console.log('mix2 准备：共享图例、底部工具箱、PNG 下载、饼图系列名称与百分比、命名堆叠、轴提示、平铺、六系列编辑、负数拒绝、关闭编辑层、还原及拖出孤岛通过。');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
