// 行高和属性组填充的公开能力回归：使用真实 Edge，数据仅为本地草稿。
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const root = path.resolve(__dirname, '..');
const { build } = require(require.resolve('esbuild', { paths: [path.dirname(require.resolve('vite', { paths: [path.join(root, 'apps/docs')] }))] }));
const { chromium } = require(path.join(process.env.USERPROFILE, '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const out = path.join(root, 'logs/table-row-heights');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const model = await build({ entryPoints: [path.join(root, 'packages/react/src/components/Table/rowHeights.ts')], bundle: true, platform: 'node', format: 'cjs', write: false });
  const mod = { exports: {} };
  new Function('module', 'exports', model.outputFiles[0].text)(mod, mod.exports);
  const layout = mod.exports.createRowHeightLayout([{ key: 'a' }, { key: 'b' }, { key: 'c' }, { key: 'd' }], 80, { a: 56, b: 120, c: NaN, d: -1 }, 28);
  assert.deepEqual(layout.offsets, [0, 56, 176, 256, 336]);
  assert.deepEqual([-5, 0, 55, 56, 175, 176, 336].map(layout.indexAt), [0, 0, 0, 1, 1, 2, 3]);
  console.log('PASS 不等行高累计偏移、边界二分、无效高度回退');
  const bundled = await build({ stdin: { resolveDir: path.join(root, 'apps/docs'), loader: 'tsx', contents: `
    import React,{useMemo,useRef,useState} from 'react'; import {createRoot} from 'react-dom/client';
    import {Table} from '../../packages/react/src/components/Table/Table';
    import {createWorksheetPlugin} from '../../packages/react/src/components/Table/worksheet';
    import '../../packages/react/src/styles.css';
    import '../../packages/react/src/components-extra.css';
    const initial=()=>Array.from({length:500},(_,id)=>({id,code:'款式'+id,group:{values:id===0?['红色','L']:id===4?['蓝色']:[]}}));
    const initialHeights=()=>Object.fromEntries(Array.from({length:500},(_,id)=>[id,id%3===0?120:id%3===1?56:80]));
    function App(){
      const [rows,setRows]=useState(initial),[heights,setHeights]=useState(initialHeights),[controlled,setControlled]=useState(true),[resizable,setResizable]=useState(true),[mode,setMode]=useState('dom'),[showIndex,setShowIndex]=useState(true);
      const ref=useRef(null),history=useRef([]);
      const plugin=useMemo(()=>createWorksheetPlugin({onChange:setRows,isEmpty:(v,r,c)=>{if(window.rejectEmpty)throw Error('判空失败');return c.key==='group'?v.values.length===0:v==null||v==='';},onError:e=>window.handled=e.message}),[]);
      window.api=()=>ref.current;window.rows=rows;window.heights=heights;window.setHeights=setHeights;window.setRows=setRows;window.setControlled=setControlled;window.setResizable=setResizable;window.setMode=setMode;window.setShowIndex=setShowIndex;
      window.undoHeight=()=>setHeights(history.current.pop());
      window.select=(id,key='group')=>ref.current.getPluginApi('cellSelection').setRange({anchor:{rowKey:id,columnKey:key},focus:{rowKey:id,columnKey:key}});
      const columns=[{key:'code',title:'款式资料编号',dataIndex:'code',width:300,fixed:'left',editable:true,required:true},{key:'group',title:'颜色 / 尺码（组合属性）',dataIndex:'group',width:800,editable:{editRender:()=>null},render:v=>v.values.join(' / ')},{key:'notes',title:'多行内容',width:240,ellipsis:false,render:()=>Array.from({length:10},(_,i)=><div key={i}>属性说明 {i}</div>)}];
      return <main><h2>工作表：500 行、可变行高与属性组</h2><Table ref={ref} rowKey="id" showIndex={showIndex} dataSource={rows} columns={columns} plugins={[plugin]} height={400} size="small" striped={false} rowHeight={80} rowHeights={controlled?heights:undefined} rowResizable={resizable} minRowHeight={56} maxRowHeight={480} renderMode={mode} onRowHeightChange={(r,h,index)=>{window.commits=(window.commits||[]).concat({id:r.id,height:h,index});history.current.push(heights);if(controlled)setHeights({...heights,[r.id]:h});}}/></main>;
    } createRoot(document.getElementById('root')).render(<App/>);
  ` }, bundle: true, write: false, outdir: 'out', format: 'iife', jsx: 'automatic' });
  const js = bundled.outputFiles.find(f => f.path.endsWith('.js')).text;
  const css = bundled.outputFiles.find(f => f.path.endsWith('.css')).text;
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(`<!doctype html><meta charset="utf-8"><style>${css}</style><div id="root"></div><script>${js}</script>`); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1100, height: 700 } });
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:' + server.address().port);
    await page.locator('tr[data-row-key="0"]').waitFor();
    const row = id => page.locator('tr[data-row-key="' + id + '"]');
    const locate = async id => {
      assert.equal(await page.evaluate(id => window.api().scrollToRow(id), id), true);
      await page.waitForFunction(id => {
        const r = document.querySelector('tr[data-row-key="' + id + '"]'), v = document.querySelector('.sia-table__viewport');
        if (!r) return false;
        const a = r.getBoundingClientRect(), b = v.getBoundingClientRect();
        return a.top >= b.top + document.querySelector('thead').offsetHeight - 1 && a.bottom <= b.top + v.clientHeight + 1;
      }, id);
    };
    assert.equal(Math.round((await row(0).boundingBox()).height), 120);
    assert.equal(Math.round((await row(1).boundingBox()).height), 56);
    await page.locator('.sia-table__viewport').evaluate(e => { e.scrollLeft = 60; });
    for (const id of [0, 51, 250, 499, 0]) await locate(id);
    assert.equal(await page.locator('.sia-table__viewport').evaluate(e => e.scrollLeft), 60);
    assert.ok(await page.locator('tr[data-row-key]').count() < 30);
    console.log('PASS 500 行不等高度虚拟滚动、末行/首行定位、固定列、横向位置保留、多行内容不撑高');
    const handle = row(0).getByRole('separator', { name: '调整行高' });
    const box = await handle.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + 2);
    await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2, box.y + 42, { steps: 5 });
    assert.equal(await page.evaluate(() => (window.commits || []).length), 0);
    await page.mouse.up();
    await page.waitForFunction(() => window.heights[0] === 160);
    assert.equal(await page.evaluate(() => window.commits.length), 1);
    assert.equal(Math.round((await row(0).boundingBox()).height), 160);
    await page.evaluate(() => window.undoHeight());
    await page.waitForFunction(() => window.heights[0] === 120);
    console.log('PASS 指针拖动预览不提交、结束仅通知一次、受控行高及业务撤销回填');
    await handle.focus();
    await page.keyboard.press('ArrowUp');
    await page.waitForFunction(() => window.heights[0] === 110);
    const cancelBox = await handle.boundingBox();
    await page.mouse.move(cancelBox.x + 20, cancelBox.y + 2);
    await page.mouse.down();
    await page.mouse.move(cancelBox.x + 20, cancelBox.y + 55);
    await page.keyboard.press('Escape');
    await page.mouse.up();
    assert.equal(await page.evaluate(() => window.commits.length), 2);
    assert.equal(Math.round((await row(0).boundingBox()).height), 110);
    console.log('PASS 键盘调整与 Esc 取消回滚');
    await page.evaluate(() => window.setHeights({ ...window.heights, 0: 56 }));
    await page.waitForFunction(() => window.heights[0] === 56);
    await handle.focus();
    await page.keyboard.press('ArrowUp');
    assert.equal(await page.evaluate(() => window.commits.length), 2);
    await page.evaluate(() => window.setHeights({ ...window.heights, 0: 480 }));
    await page.waitForFunction(() => window.heights[0] === 480);
    await handle.focus();
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.evaluate(() => window.commits.length), 2);
    await page.evaluate(() => window.setHeights({ ...window.heights, 0: 110 }));
    await page.waitForFunction(() => window.heights[0] === 110);
    console.log('PASS 高度上下界不越界、不产生无效提交');
    await page.evaluate(() => window.select(0));
    assert.equal(await page.evaluate(() => window.api().getPluginApi('worksheet').fillDown()), true);
    await page.waitForFunction(() => window.rows[3].group.values.length === 2);
    assert.deepEqual(await page.evaluate(() => window.rows[4].group.values), ['蓝色']);
    await page.evaluate(() => window.api().getPluginApi('worksheet').undo());
    await page.waitForFunction(() => window.rows[1].group.values.length === 0);
    await page.evaluate(() => window.api().getPluginApi('worksheet').redo());
    await page.waitForFunction(() => window.rows[3].group.values.length === 2);
    console.log('PASS 组合属性空值向下填充、遇非空停止、整次撤销恢复');
    await page.evaluate(() => { window.select(5); });
    assert.equal(await page.evaluate(() => window.api().getPluginApi('worksheet').fillDown()), false);
    await page.evaluate(() => { window.select(0); window.rejectEmpty=true; });
    assert.equal(await page.evaluate(() => window.api().getPluginApi('worksheet').fillDown()), false);
    assert.equal(await page.evaluate(() => window.handled), '判空失败');
    await page.evaluate(() => { window.rejectEmpty=false; });
    console.log('PASS 空属性组不填充、业务判空异常取消并通知');
    await page.evaluate(() => { window.setShowIndex(false); window.select(0, 'code'); });
    await page.waitForFunction(() => {
      const handle=document.querySelector('.sia-table__worksheet-handle');
      if(!handle)return false;
      const rect=handle.getBoundingClientRect();
      return document.elementFromPoint(rect.right-2,rect.bottom-2)?.closest('.sia-table__worksheet-handle')===handle;
    });
    console.log('PASS 隐藏序号列时，行高柄不遮挡首列的填充柄');
    // 多格选择的内容区禁止鼠标事件，填充柄仍应命中并能实际拖动。
    await row(0).locator('td[data-column-key="code"]').click();
    await row(1).locator('td[data-column-key="code"]').click({ modifiers: ['Shift'] });
    const multiHandle = page.getByRole('button', { name: '拖拽填充；双击自动填充下方连续空单元格', exact: true });
    const multiBox = await multiHandle.boundingBox();
    assert.equal(await multiHandle.evaluate(el => { const b=el.getBoundingClientRect(); return document.elementFromPoint(b.x+b.width/2,b.y+b.height/2)===el; }), true);
    const fillTarget = await row(2).locator('td[data-column-key="code"]').boundingBox();
    await page.mouse.move(multiBox.x+multiBox.width/2,multiBox.y+multiBox.height/2);
    await page.mouse.down();
    await page.mouse.move(fillTarget.x+50,fillTarget.y+20,{ steps: 8 });
    await page.mouse.up();
    await page.waitForFunction(() => window.rows[2].code === '款式0');
    await page.evaluate(() => window.api().getPluginApi('worksheet').undo());
    await page.waitForFunction(() => window.rows[2].code === '款式2');
    console.log('PASS 多格选区填充柄命中、真实拖拽循环填充和撤销');
    await page.evaluate(() => window.setShowIndex(true));
    await page.evaluate(() => { window.setRows([...window.rows].reverse()); });
    await locate(0);
    assert.equal(Math.round((await row(0).boundingBox()).height), 110);
    await locate(499);
    await page.evaluate(() => window.setMode('canvas'));
    await locate(250);
    assert.equal(await page.locator('canvas').count(), 0);
    assert.equal(await page.evaluate(() => window.api().focusCell(499, 'notes', { highlight: false })), true);
    console.log('PASS 排序后按键恢复高度、Canvas 自动回退 DOM、远端单元格定位');
    await page.screenshot({ path: path.join(out, '01-variable-rows.png'), fullPage: true });
    // 删除或筛选到少量结果时，旧的较大滚动位置不能让新结果消失。
    await page.evaluate(() => window.setRows(window.rows.slice(0, 3)));
    await locate(499);
    assert.equal(await page.locator('tr[data-row-key]').count(), 3);
    await page.evaluate(() => { window.setControlled(false); window.setMode('dom'); });
    await row(499).getByRole('separator').focus();
    await page.keyboard.press('ArrowDown');
    await page.waitForFunction(() => Math.round(document.querySelector('tr[data-row-key="499"]').getBoundingClientRect().height) === 90);
    await page.evaluate(() => window.setResizable(false));
    await page.waitForFunction(() => !document.querySelector('.sia-table__row-resize-handle'));
    await page.evaluate(() => window.setRows([]));
    await page.getByText('暂无数据').waitFor();
    console.log('PASS 筛选少量数据、非受控行高、关闭调整入口、空表');
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await new Promise(resolve => server.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode = 1; });
