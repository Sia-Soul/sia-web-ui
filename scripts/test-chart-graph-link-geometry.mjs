import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const js=ts.transpileModule(fs.readFileSync('packages/react/src/components/graphLinkGeometry.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {graphLinkGeometry}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const a={x:100,y:100},b={x:300,y:100};
const forward=graphLinkGeometry(a,b,{arrow:true,targetRadius:15,offset:4});
assert.equal(forward.path,'M 100 104 Q 200 104 300 104');
assert.equal(forward.arrow,'283,104 268,109 268,99');
const reverse=graphLinkGeometry(b,a,{arrow:true,targetRadius:25,offset:4});
assert.equal(reverse.path,'M 300 96 Q 200 96 100 96');
assert.equal(reverse.arrow,'127,96 142,91 142,101');
const curve=graphLinkGeometry(a,b,{arrow:true,curvature:.2,targetRadius:15});
assert.equal(curve.path,'M 100 100 Q 200 140 300 100');
assert.ok(!curve.arrow.includes('NaN'));
assert.equal(graphLinkGeometry(a,a,{arrow:true}).arrow,undefined);
assert.equal(graphLinkGeometry(a,b).arrow,undefined);
assert.deepEqual(a,{x:100,y:100});assert.deepEqual(b,{x:300,y:100});
console.log('有向连线：终点半径避让、10×15 箭头、反向边 ±4 偏移、曲线切线与重合端点通过。');
